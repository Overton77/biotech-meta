// Usage: node gen-params.mjs <final.graphql> <params.json> <out-params.json> <out-label-checks.cypher>
// Derives relationship class lists from the final SDL (field description "class: asserted|derived|structural", else the
// properties type family) and merges them as a UNION into the params file (W00 lists kept). Also emits archetype-label checks:
// a node with a primary label must carry every label its @node declares (CH-K-10b, CH-K-13: one archetype per node).
import { readFileSync, writeFileSync } from "node:fs";
import { parse, Kind } from "graphql";
const [sdl, pin, pout, lout] = process.argv.slice(2);
const doc = parse(readFileSync(sdl, "utf8")); const P = JSON.parse(readFileSync(pin, "utf8"));
const arg = (d, n) => (d.arguments || []).find(a => a.name.value === n);
const cls = new Map(); const nodes = [];
for (const d of doc.definitions) {
  if (d.kind !== Kind.OBJECT_TYPE_DEFINITION) continue;
  const nd = (d.directives || []).find(x => x.name.value === "node"); if (!nd) continue;
  const la = arg(nd, "labels"); nodes.push(la ? la.value.values.map(v => v.value) : [d.name.value]);
  for (const f of d.fields || []) {
    const rel = (f.directives || []).find(x => x.name.value === "relationship"); if (!rel) continue;
    const t = arg(rel, "type").value.value; const p = arg(rel, "properties")?.value.value || "";
    const desc = (f.description?.value || "").toLowerCase();
    let c = (desc.match(/class:\s*(asserted|derived|structural|legacy)/) || [])[1];
    if (!c) c = /Asserted|StateEpisode|Role|Usage|StepDose|MediaLink|Authorization/.test(p) ? "asserted" : /Derived|Projection|Support|Resolution/.test(p) ? "derived" : "structural";
    const s = cls.get(t) || new Set(); s.add(c); cls.set(t, s);
  }
}
const asserted = [...cls].filter(([t, s]) => s.has("asserted")).map(([t]) => t);
const derived = [...cls].filter(([t, s]) => s.has("derived") && !s.has("asserted")).map(([t]) => t);
const mixed = [...cls].filter(([t, s]) => s.has("derived") && s.has("asserted")).map(([t]) => t);
const legacy = [...cls].filter(([t, s]) => s.has("legacy")).map(([t]) => t);
const uni = (a, b) => [...new Set([...(a || []), ...b])].sort();
P.assertedTypes = uni(P.assertedTypes, asserted).filter(t => !["IDENTIFIED_BY"].includes(t)); P.derivedTypes = uni(P.derivedTypes, derived); P.episodeTypes = uni(P.episodeTypes, asserted);
P._gen = { source: "gen-params.mjs from final SDL", mixedClassTypes: mixed, legacyTypes: legacy, generatedAt: new Date().toISOString() };
writeFileSync(pout, JSON.stringify(P, null, 1));
let txt = "// Generated by gen-params.mjs from the final SDL: every primary label carries the labels its @node declares (one archetype per node).\n";
for (const L of nodes) if (L.length > 1) txt += `// V-F5-LBL-${L[0]}\nMATCH (n:${L[0]}) WHERE NOT (${L.slice(1).map(l => `n:${l}`).join(" AND ")}) RETURN 'V-F5-LBL' AS check, '${L[0]}' AS label, n.uid AS uid, labels(n) AS labels;\n`;
const ARCH = ["Entity","VersionedState","Occurrence","InformationArtifact","Assertion","EvidenceAssessment"];
txt += `// V-F5-ARCH-1: exactly one archetype label per node that carries any\nMATCH (n) WITH n, [l IN labels(n) WHERE l IN ${JSON.stringify(ARCH)}] AS a WHERE size(a) <> 1 AND size(labels(n)) > 0 RETURN 'V-F5-ARCH-1' AS check, n.uid AS uid, labels(n) AS labels;\n`;
txt += `// V-F5-ARCH-2: a uid-bearing node carries an archetype label (otherwise the archetype uid constraint cannot see it)\nMATCH (n) WHERE n.uid IS NOT NULL AND none(l IN labels(n) WHERE l IN ${JSON.stringify(ARCH)}) RETURN 'V-F5-ARCH-2' AS check, n.uid AS uid, labels(n) AS labels;\n`;
writeFileSync(lout, txt);
console.log(`asserted ${P.assertedTypes.length}, derived ${P.derivedTypes.length}, mixed ${mixed.length} (${mixed.join(",")}), legacy ${legacy.join(",")}; label checks ${nodes.filter(L => L.length > 1).length}`);
